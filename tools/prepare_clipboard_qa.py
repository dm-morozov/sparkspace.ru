"""Build isolated clipboard QA fixtures; never uses the operating-system clipboard."""
from pathlib import Path
import hashlib
import re

ROOT = Path(__file__).resolve().parents[1]
PUBLIC = ROOT / 'dist/public'
OUT = ROOT / 'design/qa-stage38'
BOOTSTRAP = r'''<script>
(() => {
  'use strict';
  const mode = '__MODE__';
  const state = {mode, calls: 0, status: 'installing', systemClipboard: false};
  Object.defineProperty(window, 'clipboardQA', {value: state, writable: false});
  function syncState() {
    const label = document.getElementById('clipboard-qa-label');
    if (!label) return;
    label.dataset.qaCalls = String(state.calls);
    label.dataset.qaStatus = state.status;
    label.dataset.qaMode = state.mode;
  }
  let installed = false;
  const stub = Object.freeze({writeText() {
    state.calls += 1;
    state.status = 'pending';
    syncState();
    return new Promise((resolve, reject) => {
      setTimeout(() => {
        if (mode === 'reject') {
          state.status = 'rejected';
          syncState();
          reject(new Error('Isolated QA rejection'));
        } else {
          state.status = 'resolved-no-op';
          syncState();
          resolve();
        }
      }, mode === 'delayed' ? 3000 : 100);
    });
  }});
  try {
    Object.defineProperty(navigator, 'clipboard', {value: stub, configurable: false, writable: false});
    installed = Object.getOwnPropertyDescriptor(navigator, 'clipboard').value === stub;
    state.status = installed ? 'ready' : 'blocked';
  } catch {
    state.status = 'blocked';
  }
  // Block navigation and form submission: this fixture exercises local controls only.
  document.addEventListener('click', (event) => {
    if (event.target.closest('a')) event.preventDefault();
  }, true);
  document.addEventListener('submit', event => event.preventDefault(), true);
  document.addEventListener('DOMContentLoaded', () => {
    syncState();
    if (!installed) {
      document.querySelectorAll('button,input,textarea,select').forEach(control => { control.disabled = true; });
      const banner = document.getElementById('clipboard-qa-label');
      banner.textContent = 'QA заблокирована: изолированный clipboard stub не установлен. Contact context не загружен.';
      return;
    }
    const script = document.createElement('script');
    script.src = new URL('contact-context.js', window.location.href).href;
    script.onerror = () => { state.status = 'script-load-error'; syncState(); };
    document.body.appendChild(script);
  }, {once: true});
})();
</script>'''


def main():
    html = (PUBLIC / 'contacts.html').read_text(encoding='utf-8')
    if re.search(r'<base\b', html, re.I):
        raise ValueError('Unexpected existing base')
    pattern = r'<script\b[^>]*src=["\'](?:\./)?stage30-contact-context\.js[^"\']*["\'][^>]*>\s*</script>'
    html, count = re.subn(pattern, '', html)
    if count != 1:
        raise ValueError('Expected exactly one contact context script')
    OUT.mkdir(exist_ok=True)
    script = (PUBLIC / 'stage30-contact-context.js').read_bytes()
    (OUT / 'contact-context.js').write_bytes(script)
    for mode in ('success', 'reject', 'delayed'):
        page = html.replace('<head>', '<head>\n<base href="../">\n' + BOOTSTRAP.replace('__MODE__', mode), 1)
        label = ('<aside id="clipboard-qa-label" style="padding:12px;background:#fff4cf;color:#182039;font:16px/1.5 sans-serif">'
                 'Локальная QA: ' + mode + '. Системный буфер не используется. Ссылки и отправка отключены. '
                 'Проверяются только состояния интерфейса.</aside>')
        page = re.sub(r'(<body\b[^>]*>)', lambda m: m[1] + label, page, count=1)
        (OUT / ('clipboard-' + mode + '.html')).write_text(page, encoding='utf-8')
    sha = hashlib.sha256(script).hexdigest()
    (OUT / 'README.md').write_text('''# Isolated clipboard QA

Generated by tools/prepare_clipboard_qa.py from current dist/public/contacts.html.
The contact-context.js file is an unchanged byte copy of the actual public script.
SHA-256: ''' + sha + '''

Modes: clipboard-success.html (100 ms no-op resolve), clipboard-reject.html
(100 ms rejection), clipboard-delayed.html (3000 ms no-op resolve).
Append normal whitelisted service/format query parameters if needed.

The stub does not accept, retain, log or transmit the text argument. It records
only mode, call count and status in window.clipboardQA and the QA label's
data-qa-mode/data-qa-calls/data-qa-status attributes. It does not read or write
the OS clipboard. Object.defineProperty installs an immutable own clipboard
property before context code can load. If installation/verification fails, the
context code is not loaded and form controls are disabled. Links and submits are
blocked in the fixture, including mailto, Telegram and MAX.

The public textarea content is initialized by the unchanged application script.
Never enter private material. Styles and shared scripts resolve to design/ via
base; the tested context script resolves explicitly to this fixture directory.

Manual checks: keyboard activate copy, observe focus after async resolve/reject;
clear textarea and activate (stub calls must not increase); delayed copy then
repeat activation (check calls and aria-disabled state); on rejection verify selection
and visible status. These checks establish UI behavior with a stub, not clipboard
permission compatibility or a real successful OS copy. No production artifacts
or runtime code are changed by this helper.
''', encoding='utf-8')
    print('Created three isolated fixtures; context SHA-256:', sha)


if __name__ == '__main__':
    main()
